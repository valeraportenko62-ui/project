/*
# CENTRAL WEBSITE: scalable core schema (BIGINT IDs + partition-ready tables)

1. Purpose
   Lays the database foundation for a single-domain content platform
   ("CENTRAL WEBSITE") designed to scale past 1,000,000,000 rows without
   re-architecting. All large tables use 8-byte BIGINT identity IDs and are
   declared as hash-partitioned tables (16 partitions) so data is distributed
   from day one and index maintenance stays flat as volume grows.

2. New Tables
   - `verticals` — the 6 content verticals (Informational, Reference,
     Educational, Encyclopedic, Catalogs, Scientific). Small lookup table,
     not partitioned.
     Columns: id (bigint identity, PK), slug (unique), name, description,
     target_volume (text benchmark, e.g. "10M+"), sort_order, created_at.
   - `categories` — per-vertical taxonomy tree. Not partitioned (small).
     Columns: id (bigint identity, PK), vertical_id (FK -> verticals),
     slug, name, parent_category_id (self FK), created_at.
   - `entries` — the main content rows. PARTITION BY HASH (id), 16 partitions.
     Columns: id (bigint identity, PK), vertical_id (FK), slug, title, summary,
     content, status (draft|published|archived), locale, source_url,
     published_at, metadata (jsonb), created_at, updated_at.
   - `relations` — graph edges between entries. PARTITION BY HASH (id), 16
     partitions. Columns: id (bigint identity, PK), parent_entry_id (FK ->
     entries), child_entry_id (FK -> entries), relation_type
     (parent_child|related|cites|translates), created_at.
   - `ingestion_queue` — ingestion pipeline jobs. PARTITION BY HASH (id), 16
     partitions. Columns: id (bigint identity, PK), vertical_id (FK),
     source_type, source_url, payload (jsonb), status
     (pending|processing|done|failed), attempts, last_error, created_at,
     processed_at.

3. Indexes (composite, tuned for cursor pagination on the BIGINT key)
   - entries: (vertical_id, status, id DESC), (vertical_id, id DESC),
     (status, published_at DESC, id DESC), (vertical_id, slug)
   - categories: (vertical_id, id), (parent_category_id)
   - relations: (parent_entry_id, relation_type, id),
     (child_entry_id, relation_type, id)
   - ingestion_queue: (status, id), (vertical_id, status, id)

4. Security
   - RLS enabled on all 5 tables.
   - This app has no sign-in: it is a single-tenant, publicly readable content
     platform with a unified admin. Policies therefore target `anon,
     authenticated` and allow read + write, which is intentional for this
     shared/public data. Four policies per table (SELECT/INSERT/UPDATE/DELETE),
     never FOR ALL.
   - GRANTs: SELECT/INSERT/UPDATE/DELETE on all tables to `anon` and
     `authenticated`, plus sequence usage so identity-ID inserts work.

5. Notes
   - IDs are GENERATED BY DEFAULT AS IDENTITY so callers may supply explicit
     IDs (bulk ingestion) or omit them (auto-increment).
   - Hash partitioning (not range) is used so inserts never fail on missing
     partitions and rows are evenly spread across 16 child tables; partitions
     can later be split onto separate tablespaces without app changes.
   - Unique slugs are enforced per-vertical via composite index; global
     uniqueness on a partitioned table would require the partition key.
*/

-- ---------------------------------------------------------------- verticals
CREATE TABLE IF NOT EXISTS verticals (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug text NOT NULL UNIQUE,
  name text NOT NULL,
  description text,
  target_volume text NOT NULL DEFAULT '10M+',
  sort_order int NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------- categories
CREATE TABLE IF NOT EXISTS categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vertical_id bigint NOT NULL REFERENCES verticals(id),
  slug text NOT NULL,
  name text NOT NULL,
  parent_category_id bigint REFERENCES categories(id),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS categories_vertical_id_id_idx ON categories (vertical_id, id);
CREATE INDEX IF NOT EXISTS categories_parent_idx ON categories (parent_category_id);

-- ------------------------------------------------------------------- entries
CREATE TABLE IF NOT EXISTS entries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vertical_id bigint NOT NULL REFERENCES verticals(id),
  slug text NOT NULL,
  title text NOT NULL,
  summary text,
  content text,
  status text NOT NULL DEFAULT 'draft'
    CHECK (status IN ('draft', 'published', 'archived')),
  locale text NOT NULL DEFAULT 'en',
  source_url text,
  published_at timestamptz,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
) PARTITION BY HASH (id);

CREATE INDEX IF NOT EXISTS entries_vertical_status_id_idx ON entries (vertical_id, status, id DESC);
CREATE INDEX IF NOT EXISTS entries_vertical_id_idx ON entries (vertical_id, id DESC);
CREATE INDEX IF NOT EXISTS entries_status_published_idx ON entries (status, published_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS entries_vertical_slug_idx ON entries (vertical_id, slug);

DO $$
DECLARE i int;
BEGIN
  FOR i IN 0..15 LOOP
    EXECUTE format(
      'CREATE TABLE IF NOT EXISTS entries_p%s PARTITION OF entries FOR VALUES WITH (MODULUS 16, REMAINDER %s)',
      lpad(i::text, 2, '0'), i
    );
  END LOOP;
END $$;

-- ----------------------------------------------------------------- relations
CREATE TABLE IF NOT EXISTS relations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_entry_id bigint NOT NULL REFERENCES entries(id),
  child_entry_id bigint NOT NULL REFERENCES entries(id),
  relation_type text NOT NULL
    CHECK (relation_type IN ('parent_child', 'related', 'cites', 'translates')),
  created_at timestamptz NOT NULL DEFAULT now()
) PARTITION BY HASH (id);

CREATE INDEX IF NOT EXISTS relations_parent_type_id_idx ON relations (parent_entry_id, relation_type, id DESC);
CREATE INDEX IF NOT EXISTS relations_child_type_id_idx ON relations (child_entry_id, relation_type, id DESC);

DO $$
DECLARE i int;
BEGIN
  FOR i IN 0..15 LOOP
    EXECUTE format(
      'CREATE TABLE IF NOT EXISTS relations_p%s PARTITION OF relations FOR VALUES WITH (MODULUS 16, REMAINDER %s)',
      lpad(i::text, 2, '0'), i
    );
  END LOOP;
END $$;

-- ----------------------------------------------------------- ingestion_queue
CREATE TABLE IF NOT EXISTS ingestion_queue (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vertical_id bigint NOT NULL REFERENCES verticals(id),
  source_type text NOT NULL DEFAULT 'manual',
  source_url text,
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'processing', 'done', 'failed')),
  attempts int NOT NULL DEFAULT 0,
  last_error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  processed_at timestamptz
) PARTITION BY HASH (id);

CREATE INDEX IF NOT EXISTS ingestion_status_id_idx ON ingestion_queue (status, id DESC);
CREATE INDEX IF NOT EXISTS ingestion_vertical_status_id_idx ON ingestion_queue (vertical_id, status, id DESC);

DO $$
DECLARE i int;
BEGIN
  FOR i IN 0..15 LOOP
    EXECUTE format(
      'CREATE TABLE IF NOT EXISTS ingestion_queue_p%s PARTITION OF ingestion_queue FOR VALUES WITH (MODULUS 16, REMAINDER %s)',
      lpad(i::text, 2, '0'), i
    );
  END LOOP;
END $$;

